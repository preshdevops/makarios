import json

data = json.load(open('android/app/src/main/assets/declarations_seed.json', encoding='utf-8'))

kt_lines = []
kt_lines.append("package com.makarios.app.data")
kt_lines.append("")
kt_lines.append("import com.makarios.app.data.bible.ScriptureText")
kt_lines.append("")
kt_lines.append("data class SeedVerse(")
kt_lines.append("    val ref: String,")
kt_lines.append("    val text: String")
kt_lines.append(")")
kt_lines.append("")
kt_lines.append("data class SeedDeclaration(")
kt_lines.append("    val declaration: String,")
kt_lines.append("    val topic: String,")
kt_lines.append("    val verses: List<SeedVerse>")
kt_lines.append(") {")
kt_lines.append("    val bestVerse: SeedVerse get() = verses.first()")
kt_lines.append("}")
kt_lines.append("")
kt_lines.append("object SeedDeclarations {")
kt_lines.append("    val entries: List<SeedDeclaration> = listOf(")

for d in data:
    decl_escaped = d['declaration'].replace('"', '\\"')
    topic_escaped = d['topic'].replace('"', '\\"')
    kt_lines.append(f'        SeedDeclaration(')
    kt_lines.append(f'            declaration = "{decl_escaped}",')
    kt_lines.append(f'            topic = "{topic_escaped}",')
    kt_lines.append(f'            verses = listOf(')
    for v in d['verses']:
        ref_norm = v['ref'] # e.g. "1 John 4:18"
        text_esc = v['text'].replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$')
        kt_lines.append(f'                SeedVerse("{ref_norm}", "{text_esc}"),')
    kt_lines.append(f'            )')
    kt_lines.append(f'        ),')

kt_lines.append("    )")
kt_lines.append("")
kt_lines.append("    fun asAffirmations(): List<Affirmation> = entries.mapIndexed { idx, item ->")
kt_lines.append("        val best = item.bestVerse")
kt_lines.append("        Affirmation(")
kt_lines.append("            id = \"seed-${idx + 1}\",")
kt_lines.append("            declaration = item.declaration,")
kt_lines.append("            scriptureText = best.text,")
kt_lines.append("            reference = ScriptureText.normalizeReference(best.ref),")
kt_lines.append("            context = \"Reviewed declaration standing on God's word.\",")
kt_lines.append("            category = item.topic,")
kt_lines.append("            tone = AffirmationTone.STILL,")
kt_lines.append("            imageUrl = \"\",")
kt_lines.append("            isFavorite = false")
kt_lines.append("        )")
kt_lines.append("    }")
kt_lines.append("")
kt_lines.append("    fun asBankEntries(): List<BankEntry> = entries.map { item ->")
kt_lines.append("        BankEntry(")
kt_lines.append("            declaration = item.declaration,")
kt_lines.append("            aliases = emptyList(),")
kt_lines.append("            references = item.verses.map { it.ref },")
kt_lines.append("            theme = item.topic.lowercase()")
kt_lines.append("        )")
kt_lines.append("    }")
kt_lines.append("}")
kt_lines.append("")

with open('android/app/src/main/java/com/makarios/app/data/SeedDeclarations.kt', 'w', encoding='utf-8') as f:
    f.write('\n'.join(kt_lines))

print("Successfully generated SeedDeclarations.kt")
